GO
USE QL_GIAOVIEN
GO

CREATE TABLE COSO
(
	MACOSO VARCHAR(10) NOT NULL PRIMARY KEY,
	TENCOSO NVARCHAR(30)
)

CREATE TABLE DONVI
(
	MADONVI VARCHAR(10) NOT NULL PRIMARY KEY,
	TENDONVI NVARCHAR(30),
	MACOSO VARCHAR(10) NOT NULL,
	CONSTRAINT FK_DONVI FOREIGN KEY (MACOSO) REFERENCES COSO(MACOSO)
)

CREATE TABLE GV
(
	MAGV VARCHAR(10) NOT NULL PRIMARY KEY,
	HOTEN NVARCHAR(30),
	SDT VARCHAR(10),
	GHICHU NVARCHAR(30),
	MADONVI VARCHAR(10) NOT NULL,
	CONSTRAINT FK_GV FOREIGN KEY (MADONVI) REFERENCES DONVI(MADONVI)
)

